from typing import Protocol

from portal_auth.domain.sso import SignInAttempt
from portal_auth.domain.user import ExternalIdentity, User


class UserRepository(Protocol):
    async def get(self, user_id: str) -> User | None: ...
    async def by_username(self, username: str) -> User | None: ...
    async def add(self, user: User) -> None: ...
    async def count(self) -> int: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...

    def verify(self, password_hash: str | None, password: str) -> bool:
        """Without a stored hash, still spends the same time and returns False (no user enumeration)."""
        ...


class IdentityProvider(Protocol):
    """Corporate IdP. `authorize_url` sends the browser there; `exchange` turns the code it sends back into an identity."""

    async def authorize_url(self, attempt: SignInAttempt) -> str: ...
    async def exchange(self, code: str, attempt: SignInAttempt) -> ExternalIdentity: ...
